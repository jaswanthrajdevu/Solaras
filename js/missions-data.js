(function () {
  const allowedAgencyGroups = new Set(['usa', 'india', 'europe', 'japan', 'china', 'russia']);
  const allowedTargets = new Set([
    'Moon',
    'Mars',
    'Venus',
    'Mercury',
    'Jupiter',
    'Saturn',
    'Outer Solar System',
    'Other'
  ]);
  const allowedCategories = new Set(['mission', 'discovery']);
  const isDevelopment = window.SOLARA_DATA?.isDevelopment;

  function validateMissions(missions) {
    const errors = [];
    if (!Array.isArray(missions)) {
      errors.push('mission data must be an array');
    } else {
      const ids = new Set();
      const names = new Set();
      const missionIds = new Set(
        missions.filter((mission) => mission?.category === 'mission').map((mission) => mission.id)
      );
      const currentYear = new Date().getFullYear();

      missions.forEach((mission, index) => {
        const label = mission?.id || `entry ${index + 1}`;
        if (!mission || typeof mission !== 'object') {
          errors.push(`${label}: record must be an object`);
          return;
        }
        if (typeof mission.id !== 'string' || !mission.id.trim()) {
          errors.push(`${label}: id is required`);
        } else if (ids.has(mission.id)) {
          errors.push(`${label}: duplicate id "${mission.id}"`);
        } else {
          ids.add(mission.id);
        }
        if (typeof mission.name !== 'string' || !mission.name.trim()) {
          errors.push(`${label}: name is required`);
        } else if (names.has(mission.name)) {
          errors.push(`${label}: duplicate name "${mission.name}"`);
        } else {
          names.add(mission.name);
        }
        if (!Number.isInteger(mission.year) || mission.year < 1957 || mission.year > currentYear) {
          errors.push(`${label}: year must be an integer from 1957 through ${currentYear}`);
        }
        if (!allowedCategories.has(mission.category)) errors.push(`${label}: unknown category "${mission.category}"`);
        if (!allowedAgencyGroups.has(mission.agencyGroup)) errors.push(`${label}: unknown agency group "${mission.agencyGroup}"`);
        if (!allowedTargets.has(mission.target)) errors.push(`${label}: unknown target "${mission.target}"`);
        ['country', 'agency', 'targetLabel', 'missionType', 'summary', 'achievement', 'outcome'].forEach((field) => {
          if (typeof mission[field] !== 'string' || !mission[field].trim()) {
            errors.push(`${label}: required field "${field}" is missing`);
          }
        });
        if (mission.relatedMissionId !== undefined && mission.relatedMissionId !== null) {
          if (mission.category !== 'discovery') {
            errors.push(`${label}: only discoveries may reference a related mission`);
          }
          if (!missionIds.has(mission.relatedMissionId)) {
            errors.push(`${label}: related mission id "${mission.relatedMissionId}" does not reference a mission`);
          }
        }
      });
    }

    if (errors.length && isDevelopment) {
      console.error('[SOLARA data] Mission validation failed:', errors);
    }
    return errors.length === 0;
  }

  if (window.SOLARA_DATA) window.SOLARA_DATA.validateMissions = validateMissions;
  validateMissions(window.SOLARA_MISSIONS);
})();
